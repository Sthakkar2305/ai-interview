"use client"

import { useEffect, useState } from "react"
import { useRouter, useParams } from "next/navigation"
import { useAuth } from "@/lib/auth-context"
import { getSupabaseClient } from "@/lib/supabase-client"
import { Button } from "@/components/ui/button"
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card"
import { Loader2, Download, AlertCircle, CheckCircle2, TrendingUp } from "lucide-react"
import {
  BarChart,
  Bar,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
  ResponsiveContainer,
  RadarChart,
  PolarGrid,
  PolarAngleAxis,
  PolarRadiusAxis,
  Radar,
} from "recharts"
import type { Database } from "@/lib/supabase-client"

type InterviewSession = Database["public"]["Tables"]["interview_sessions"]["Row"]
type InterviewFeedback = Database["public"]["Tables"]["interview_feedback"]["Row"]

export default function ResultsPage() {
  const router = useRouter()
  const params = useParams()
  const { user, loading: authLoading } = useAuth()
  const supabase = getSupabaseClient()

  const interviewId = params.id as string
  const sessionId = params.sessionId as string

  const [session, setSession] = useState<InterviewSession | null>(null)
  const [feedback, setFeedback] = useState<InterviewFeedback | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState("")
  const [generatingPDF, setGeneratingPDF] = useState(false)

  useEffect(() => {
    if (authLoading) return

    if (!user) {
      router.push("/auth/login")
      return
    }

    const fetchResults = async () => {
      try {
        // Fetch session and associated interview
        const { data: sessionData, error: sessionError } = await supabase
          .from("interview_sessions")
          .select("*, interviews(*)")
          .eq("id", sessionId)
          .eq("user_id", user.id)
          .single()

        if (sessionError) {
          setError("Failed to load session results")
          return
        }

        setSession(sessionData)

        // Fetch feedback
        const { data: feedbackData, error: feedbackError } = await supabase
          .from("interview_feedback")
          .select("*")
          .eq("session_id", sessionId)
          .single()

        if (!feedbackError && feedbackData) {
          setFeedback(feedbackData)
        }
      } catch (err) {
        setError(err instanceof Error ? err.message : "Failed to load results")
      } finally {
        setLoading(false)
      }
    }

    fetchResults()
  }, [user, authLoading, sessionId, supabase, router])

  const handleDownloadPDF = async () => {
    if (!session || !feedback) return

    setGeneratingPDF(true)
    try {
      // In production, you would generate a proper PDF using a library like jsPDF
      // For now, create a simple downloadable report
      const reportContent = `
AI INTERVIEW PLATFORM - EVALUATION REPORT
==========================================

Session ID: ${sessionId}
Date: ${new Date(session.created_at).toLocaleDateString()}

OVERALL SCORES
==============
Overall Score: ${session.overall_score || 0}/100
Passing Score: ${(session as any).interviews?.passing_marks || 70}/100
Result: ${(session.overall_score || 0) >= ((session as any).interviews?.passing_marks || 70) ? "PASS" : "FAIL"}

Knowledge Score: ${session.knowledge_score || 0}/100
Communication Score: ${session.communication_score || 0}/100
Confidence Score: ${session.confidence_score || 0}/100
Technical Depth Score: ${session.technical_depth_score || 0}/100

STRENGTHS
=========
${feedback?.strengths?.map((s) => `• ${s}`).join("\n") || "None recorded"}

AREAS FOR IMPROVEMENT
=====================
${feedback?.weaknesses?.map((w) => `• ${w}`).join("\n") || "None recorded"}

MISSED CONCEPTS
===============
${feedback?.missed_concepts?.map((m) => `• ${m}`).join("\n") || "None recorded"}

IMPROVEMENT SUGGESTIONS
=======================
${feedback?.improvement_suggestions?.map((s) => `• ${s}`).join("\n") || "None recorded"}

TIPS TO ACHIEVE 85+ SCORE
=========================
${feedback?.tips_to_improve?.map((t) => `• ${t}`).join("\n") || "None recorded"}

Generated by AI Interview Platform
`

      const blob = new Blob([reportContent], { type: "text/plain" })
      const url = window.URL.createObjectURL(blob)
      const link = document.createElement("a")
      link.href = url
      link.download = `interview-report-${sessionId}.txt`
      document.body.appendChild(link)
      link.click()
      document.body.removeChild(link)
      window.URL.revokeObjectURL(url)
    } catch (err) {
      setError("Failed to generate PDF")
    } finally {
      setGeneratingPDF(false)
    }
  }

  if (loading || authLoading) {
    return (
      <div className="flex items-center justify-center min-h-screen">
        <Loader2 className="h-8 w-8 animate-spin text-primary" />
      </div>
    )
  }

  if (!session || !feedback) {
    return (
      <div className="min-h-screen bg-background flex items-center justify-center px-4">
        <Card className="w-full max-w-md border-destructive/50">
          <CardContent className="pt-6">
            <div className="flex items-start gap-3">
              <AlertCircle className="h-5 w-5 text-destructive flex-shrink-0 mt-0.5" />
              <div>
                <p className="font-semibold text-foreground">Results Not Available</p>
                <p className="text-sm text-muted-foreground mt-1">{error || "Unable to load interview results"}</p>
                <Button className="mt-4" onClick={() => router.push("/")}>
                  Back to Home
                </Button>
              </div>
            </div>
          </CardContent>
        </Card>
      </div>
    )
  }

  const scoreData = [
    { name: "Knowledge", value: session.knowledge_score || 0 },
    { name: "Communication", value: session.communication_score || 0 },
    { name: "Confidence", value: session.confidence_score || 0 },
    { name: "Technical Depth", value: session.technical_depth_score || 0 },
  ]

  const scoreComparisonData = [
    { category: "Knowledge", score: session.knowledge_score || 0 },
    { category: "Communication", score: session.communication_score || 0 },
    { category: "Confidence", score: session.confidence_score || 0 },
    { category: "Technical", score: session.technical_depth_score || 0 },
  ]

  const overallScore = session.overall_score || 0
  const passingMarks = (session as any).interviews?.passing_marks || 70
  const isPassed = overallScore >= passingMarks

  const isExcellent = overallScore >= 85
  const isGood = overallScore >= 70 && !isExcellent
  const needsWork = overallScore < 70

  return (
    <div className="min-h-screen bg-background">
      <nav className="border-b border-border sticky top-0 bg-background/95 backdrop-blur supports-[backdrop-filter]:bg-background/60">
        <div className="max-w-7xl mx-auto px-4 h-16 flex items-center justify-between">
          <h1 className="text-2xl font-bold text-primary">Interview Results</h1>
          <Button onClick={() => router.push("/")} variant="ghost">
            Back to Dashboard
          </Button>
        </div>
      </nav>

      <main className="max-w-7xl mx-auto px-4 py-12">
        <div className="space-y-8">
          {/* Pass / Fail Status */}
          <Card className={`border-2 ${isPassed ? "border-green-500/50 bg-green-500/10" : "border-red-500/50 bg-red-500/10"}`}>
            <CardContent className="pt-6 flex justify-between items-center">
              <div>
                <h2 className={`text-2xl font-bold ${isPassed ? "text-green-600 dark:text-green-400" : "text-red-600 dark:text-red-400"}`}>
                  {isPassed ? "Result: PASS" : "Result: FAIL"}
                </h2>
                <p className="text-muted-foreground mt-1">
                  {isPassed ? "Congratulations! You have passed the interview." : "Unfortunately, you did not meet the required passing threshold."}
                </p>
              </div>
              <div className="text-right">
                <p className="text-sm font-semibold">Passing Marks Required: {passingMarks}/100</p>
              </div>
            </CardContent>
          </Card>

          {/* Overall Score Card */}
          <Card
            className={`border-2 ${
              isExcellent
                ? "border-green-500/30 bg-green-500/5"
                : isGood
                  ? "border-blue-500/30 bg-blue-500/5"
                  : "border-yellow-500/30 bg-yellow-500/5"
            }`}
          >
            <CardContent className="pt-8">
              <div className="flex items-center justify-between">
                <div>
                  <p className="text-muted-foreground text-lg mb-2">Overall Interview Score</p>
                  <div className="flex items-baseline gap-2">
                    <span className="text-7xl font-bold text-primary">{Math.round(overallScore)}</span>
                    <span className="text-3xl text-muted-foreground">/100</span>
                  </div>
                  <p className="text-sm text-muted-foreground mt-3">
                    {isExcellent && "Excellent performance! Strong candidate."}
                    {isGood && "Good performance. Room for improvement in some areas."}
                    {needsWork && "Performance needs improvement. Focus on suggested areas."}
                  </p>
                </div>
                <div className="text-right">
                  {isExcellent && <CheckCircle2 className="h-16 w-16 text-green-500 mb-2" />}
                  {isGood && <TrendingUp className="h-16 w-16 text-blue-500 mb-2" />}
                  {needsWork && <AlertCircle className="h-16 w-16 text-yellow-500 mb-2" />}
                  <p className="text-sm font-semibold">{isExcellent ? "Excellent" : isGood ? "Good" : "Fair"}</p>
                </div>
              </div>
            </CardContent>
          </Card>

          {/* Score Breakdown */}
          <div className="grid grid-cols-1 lg:grid-cols-2 gap-8">
            {/* Bar Chart */}
            <Card className="border-primary/20">
              <CardHeader>
                <CardTitle>Score Breakdown</CardTitle>
                <CardDescription>Performance across different dimensions</CardDescription>
              </CardHeader>
              <CardContent>
                <ResponsiveContainer width="100%" height={300}>
                  <BarChart data={scoreData}>
                    <CartesianGrid strokeDasharray="3 3" stroke="var(--color-border)" />
                    <XAxis dataKey="name" stroke="var(--color-muted-foreground)" />
                    <YAxis stroke="var(--color-muted-foreground)" domain={[0, 100]} />
                    <Tooltip
                      contentStyle={{
                        backgroundColor: "var(--color-card)",
                        border: `1px solid var(--color-border)`,
                      }}
                    />
                    <Bar dataKey="value" fill="var(--color-primary)" radius={[8, 8, 0, 0]} />
                  </BarChart>
                </ResponsiveContainer>
              </CardContent>
            </Card>

            {/* Radar Chart */}
            <Card className="border-primary/20">
              <CardHeader>
                <CardTitle>Performance Radar</CardTitle>
                <CardDescription>Multi-dimensional performance view</CardDescription>
              </CardHeader>
              <CardContent>
                <ResponsiveContainer width="100%" height={300}>
                  <RadarChart data={scoreComparisonData}>
                    <PolarGrid stroke="var(--color-border)" />
                    <PolarAngleAxis dataKey="category" stroke="var(--color-muted-foreground)" />
                    <PolarRadiusAxis domain={[0, 100]} stroke="var(--color-muted-foreground)" />
                    <Radar
                      name="Score"
                      dataKey="score"
                      stroke="var(--color-primary)"
                      fill="var(--color-primary)"
                      fillOpacity={0.6}
                    />
                  </RadarChart>
                </ResponsiveContainer>
              </CardContent>
            </Card>
          </div>

          {/* Strengths and Weaknesses */}
          <div className="grid grid-cols-1 lg:grid-cols-2 gap-8">
            <Card className="border-green-500/20 bg-green-500/5">
              <CardHeader>
                <CardTitle className="flex items-center gap-2 text-green-700 dark:text-green-400">
                  <CheckCircle2 className="h-5 w-5" />
                  Strengths
                </CardTitle>
              </CardHeader>
              <CardContent>
                <ul className="space-y-3">
                  {feedback?.strengths?.map((strength, idx) => (
                    <li key={idx} className="flex gap-3">
                      <span className="text-green-500 font-bold mt-0.5">✓</span>
                      <span className="text-foreground">{strength}</span>
                    </li>
                  ))}
                </ul>
              </CardContent>
            </Card>

            <Card className="border-yellow-500/20 bg-yellow-500/5">
              <CardHeader>
                <CardTitle className="flex items-center gap-2 text-yellow-700 dark:text-yellow-400">
                  <AlertCircle className="h-5 w-5" />
                  Areas for Improvement
                </CardTitle>
              </CardHeader>
              <CardContent>
                <ul className="space-y-3">
                  {feedback?.weaknesses?.map((weakness, idx) => (
                    <li key={idx} className="flex gap-3">
                      <span className="text-yellow-500 font-bold mt-0.5">!</span>
                      <span className="text-foreground">{weakness}</span>
                    </li>
                  ))}
                </ul>
              </CardContent>
            </Card>
          </div>

          {/* Missed Concepts */}
          {feedback?.missed_concepts && feedback.missed_concepts.length > 0 && (
            <Card className="border-accent/20">
              <CardHeader>
                <CardTitle>Missed Concepts</CardTitle>
                <CardDescription>Important topics not covered in your responses</CardDescription>
              </CardHeader>
              <CardContent>
                <div className="flex flex-wrap gap-2">
                  {feedback.missed_concepts.map((concept, idx) => (
                    <span key={idx} className="bg-accent/10 text-accent px-4 py-2 rounded-full text-sm">
                      {concept}
                    </span>
                  ))}
                </div>
              </CardContent>
            </Card>
          )}

          {/* Improvement Suggestions */}
          <Card className="border-primary/20">
            <CardHeader>
              <CardTitle className="flex items-center gap-2">
                <TrendingUp className="h-5 w-5 text-primary" />
                Improvement Suggestions
              </CardTitle>
              <CardDescription>Specific actions to enhance your performance</CardDescription>
            </CardHeader>
            <CardContent>
              <ol className="space-y-4">
                {feedback?.improvement_suggestions?.map((suggestion, idx) => (
                  <li key={idx} className="flex gap-4">
                    <span className="flex items-center justify-center w-8 h-8 rounded-full bg-primary/10 text-primary font-semibold flex-shrink-0">
                      {idx + 1}
                    </span>
                    <span className="text-foreground pt-0.5">{suggestion}</span>
                  </li>
                ))}
              </ol>
            </CardContent>
          </Card>

          {/* Tips to Achieve 85+ */}
          <Card className="border-green-500/20 bg-green-500/5">
            <CardHeader>
              <CardTitle className="flex items-center gap-2 text-green-700 dark:text-green-400">
                <CheckCircle2 className="h-5 w-5" />
                Tips to Achieve 85+ Score
              </CardTitle>
              <CardDescription>Key actions to elevate your performance</CardDescription>
            </CardHeader>
            <CardContent>
              <ul className="space-y-3">
                {feedback?.tips_to_improve?.map((tip, idx) => (
                  <li key={idx} className="flex gap-3">
                    <span className="text-green-500 font-bold mt-0.5">★</span>
                    <span className="text-foreground">{tip}</span>
                  </li>
                ))}
              </ul>
            </CardContent>
          </Card>

          {/* Vocabulary Upgrades */}
          {feedback?.vocabulary_upgrades && Object.keys(feedback.vocabulary_upgrades).length > 0 && (
            <Card className="border-secondary/20">
              <CardHeader>
                <CardTitle>Vocabulary Upgrades</CardTitle>
                <CardDescription>Better word choices to enhance your communication</CardDescription>
              </CardHeader>
              <CardContent>
                <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                  {Object.entries(feedback.vocabulary_upgrades as Record<string, string>).map(
                    ([oldWord, newWord], idx) => (
                      <div key={idx} className="p-4 bg-secondary/10 rounded-lg">
                        <p className="text-xs text-muted-foreground mb-1">Instead of:</p>
                        <p className="font-semibold text-foreground line-through opacity-70 mb-2">{oldWord}</p>
                        <p className="text-xs text-muted-foreground mb-1">Try:</p>
                        <p className="font-semibold text-primary">{newWord}</p>
                      </div>
                    ),
                  )}
                </div>
              </CardContent>
            </Card>
          )}

          {/* Action Buttons */}
          <div className="flex gap-4 justify-center pt-4">
            <Button onClick={handleDownloadPDF} disabled={generatingPDF} size="lg" className="gap-2">
              {generatingPDF && <Loader2 className="h-4 w-4 animate-spin" />}
              <Download className="h-4 w-4" />
              Download Report
            </Button>
            <Button variant="outline" size="lg" onClick={() => router.push("/")} className="bg-transparent">
              Back to Dashboard
            </Button>
          </div>
        </div>
      </main>
    </div>
  )
}
